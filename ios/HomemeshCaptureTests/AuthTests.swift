import XCTest
@testable import HomemeshCapture

final class AuthTests: XCTestCase {
    func testPKCEChallengeMatchesRFC7636() {
        // RFC 7636 appendix B
        XCTAssertEqual(Auth.challenge(for: "dBjftJeZ4CVP-mB92K27uhbUJU1p1r_wW1gFWFOEjXk"),
                       "E9Melhoa2OwvFrEMTJguCHaoeK1t8URWbuGJSstw-cM")
    }

    func testRandomStringsAreUrlSafeAndDistinct() {
        let a = Auth.randomString(), b = Auth.randomString()
        XCTAssertNotEqual(a, b)
        XCTAssertNil(a.rangeOfCharacter(from: CharacterSet(charactersIn: "+/=")))
    }

    private func jwt(exp: Double) -> String {
        let payload = Auth.base64url(try! JSONSerialization.data(withJSONObject: ["exp": exp]))
        return "e30.\(payload).sig"
    }

    func testExpiryAndFreshness() {
        let now = Date(timeIntervalSince1970: 1_000_000)
        XCTAssertEqual(Auth.expiry(of: jwt(exp: 1_003_600)), Date(timeIntervalSince1970: 1_003_600))
        XCTAssertTrue(Auth.isFresh(jwt(exp: 1_003_600), now: now))
        XCTAssertFalse(Auth.isFresh(jwt(exp: 1_000_060), now: now))  // inside the two-minute margin
        XCTAssertFalse(Auth.isFresh("not a jwt", now: now))
    }
}

final class FieldTests: XCTestCase {
    func testTrimmedDropsTrailingSpaceAndNewlines() {
        XCTAssertEqual("espinazo ".trimmed, "espinazo")
        XCTAssertEqual(" \thttps://x \n".trimmed, "https://x")
    }

    func testDefaultNameHasATimestamp() {
        XCTAssertTrue(Naming.defaultScanName(Date(timeIntervalSince1970: 0)).hasPrefix("Scan 19"))
    }

    func testSlugIsAValidHouseId() {
        XCTAssertEqual(Naming.slug("My House #2 "), "my-house-2")
        XCTAssertEqual(Naming.slug("Espinazo"), "espinazo")
        XCTAssertEqual(Naming.slug("!!!"), "")
        XCTAssertLessThanOrEqual(Naming.slug(String(repeating: "a", count: 100)).count, 64)
    }

    func testCaptureRoomNamesArePaddedToTheRoomCount() throws {
        let json = #"{"blob":"b","name":"n","at":1,"counts":{"rooms":3,"walls":8},"usdz":null,"rooms":["Kitchen"],"level":"L1"}"#
        let c = try JSONDecoder().decode(CaptureMeta.self, from: Data(json.utf8))
        XCTAssertEqual(c.roomNames, ["Kitchen", "", ""])
        XCTAssertEqual(c.level, "L1")
    }

    /// Contract: the app's model types read what the backend stores (tests/fixtures are generated by homemesh.fixtures).
    func testFixturesDecode() throws {
        let urls = Bundle(for: FieldTests.self).urls(forResourcesWithExtension: "json", subdirectory: nil) ?? []
        XCTAssertGreaterThanOrEqual(urls.count, 4)
        for u in urls {
            let h = try JSONDecoder().decode(HouseLite.self, from: Data(contentsOf: u))
            XCTAssertFalse(h.levels.isEmpty, u.lastPathComponent)
        }
    }

    func testPlacementDecodesWhatTheServerSends() throws {
        let json = #"""
        {"confidence":"auto","reason":"a clear match","transform":{"rotation":-37.0,"tx":1.5,"ty":2.0},"score":9.2,"source":"doorway",
         "evidence":{"openings":1},"alternatives":[{"transform":{"rotation":0,"tx":0,"ty":0},"score":1.0,"source":"name"}],
         "preview":[{"a":[0,0],"b":[4,0]}]}
        """#
        let p = try JSONDecoder().decode(Placement.self, from: Data(json.utf8))
        XCTAssertEqual(p.confidence, "auto")
        XCTAssertEqual(p.preview.first?.b, Pt(4, 0))
        XCTAssertEqual(p.alternatives.count, 1)
    }

    func testAdjustAndComposeAgree() {
        // a point of the scan, placed by T0 and then nudged, must land where the composed transform puts it
        let t0 = Transform2D(rotation: 30, tx: 2, ty: -1)
        let p = Pt(1, 2)
        let r0 = Geometry.rotate(p, degrees: t0.rotation)
        let placed = Pt(r0.x + t0.tx, r0.y + t0.ty)
        let centre = Pt(1.5, 0.5), d = Pt(0.4, -0.2), delta = 12.0
        let nudged = Geometry.adjust([Seg(a: placed, b: placed)], centre: centre, delta: delta, d: d)[0].a
        let t = Geometry.compose(t0, centre: centre, delta: delta, d: d)
        let r = Geometry.rotate(p, degrees: t.rotation)
        XCTAssertEqual(nudged.x, r.x + t.tx, accuracy: 1e-9)
        XCTAssertEqual(nudged.y, r.y + t.ty, accuracy: 1e-9)
    }
}
