import XCTest
@testable import HomemeshCapture

final class AuthTests: XCTestCase {
    func testPKCEChallengeMatchesRFC7636() {
        // RFC 7636 appendix B
        XCTAssertEqual(Auth.challenge(for: "dBjftJeZ4CVP-mB92K27uhbUJU1p1r_wW1gFWFOEjXk"),
                       "E9Melhoa2OwvFrEMTJguCHaoeK1t8URWbuGJSstw-cM")
    }

    func testRandomStringsAreUrlSafeAndDistinct() {
        let a = Auth.randomString(), b = Auth.randomString()
        XCTAssertNotEqual(a, b)
        XCTAssertNil(a.rangeOfCharacter(from: CharacterSet(charactersIn: "+/=")))
    }

    private func jwt(exp: Double) -> String {
        let payload = Auth.base64url(try! JSONSerialization.data(withJSONObject: ["exp": exp]))
        return "e30.\(payload).sig"
    }

    func testExpiryAndFreshness() {
        let now = Date(timeIntervalSince1970: 1_000_000)
        XCTAssertEqual(Auth.expiry(of: jwt(exp: 1_003_600)), Date(timeIntervalSince1970: 1_003_600))
        XCTAssertTrue(Auth.isFresh(jwt(exp: 1_003_600), now: now))
        XCTAssertFalse(Auth.isFresh(jwt(exp: 1_000_060), now: now))  // inside the two-minute margin
        XCTAssertFalse(Auth.isFresh("not a jwt", now: now))
    }
}

final class FieldTests: XCTestCase {
    func testTrimmedDropsTrailingSpaceAndNewlines() {
        XCTAssertEqual("espinazo ".trimmed, "espinazo")
        XCTAssertEqual(" \thttps://x \n".trimmed, "https://x")
    }

    func testDefaultNameHasATimestamp() {
        XCTAssertTrue(Naming.defaultScanName(Date(timeIntervalSince1970: 0)).hasPrefix("Scan 19"))
    }

    func testSlugIsAValidHouseId() {
        XCTAssertEqual(Naming.slug("My House #2 "), "my-house-2")
        XCTAssertEqual(Naming.slug("Espinazo"), "espinazo")
        XCTAssertEqual(Naming.slug("!!!"), "")
        XCTAssertLessThanOrEqual(Naming.slug(String(repeating: "a", count: 100)).count, 64)
    }

    func testCaptureRoomNamesArePaddedToTheRoomCount() throws {
        let json = #"{"blob":"b","name":"n","at":1,"counts":{"rooms":3,"walls":8},"usdz":null,"rooms":["Kitchen"],"level":"L1"}"#
        let c = try JSONDecoder().decode(CaptureMeta.self, from: Data(json.utf8))
        XCTAssertEqual(c.roomNames, ["Kitchen", "", ""])
        XCTAssertEqual(c.level, "L1")
    }

    /// Contract: the app's model types read what the backend stores (tests/fixtures are generated by homemesh.fixtures).
    func testFixturesDecode() throws {
        let urls = Bundle(for: FieldTests.self).urls(forResourcesWithExtension: "json", subdirectory: nil) ?? []
        XCTAssertGreaterThanOrEqual(urls.count, 4)
        for u in urls {
            let h = try JSONDecoder().decode(HouseLite.self, from: Data(contentsOf: u))
            XCTAssertFalse(h.levels.isEmpty, u.lastPathComponent)
        }
    }

    func testPlacementDecodesWhatTheServerSends() throws {
        let json = #"""
        {"confidence":"auto","reason":"a clear match","transform":{"rotation":-37.0,"tx":1.5,"ty":2.0},"score":9.2,"source":"doorway",
         "evidence":{"openings":1},"alternatives":[{"transform":{"rotation":0,"tx":0,"ty":0},"score":1.0,"source":"name"}],
         "preview":[{"a":[0,0],"b":[4,0]}]}
        """#
        let p = try JSONDecoder().decode(Placement.self, from: Data(json.utf8))
        XCTAssertEqual(p.confidence, "auto")
        XCTAssertEqual(p.preview.first?.b, Pt(4, 0))
        XCTAssertEqual(p.alternatives.count, 1)
    }

    func testAdjustAndComposeAgree() {
        // a point of the scan, placed by T0 and then nudged, must land where the composed transform puts it
        let t0 = Transform2D(rotation: 30, tx: 2, ty: -1)
        let p = Pt(1, 2)
        let r0 = Geometry.rotate(p, degrees: t0.rotation)
        let placed = Pt(r0.x + t0.tx, r0.y + t0.ty)
        let centre = Pt(1.5, 0.5), d = Pt(0.4, -0.2), delta = 12.0
        let nudged = Geometry.adjust([Seg(a: placed, b: placed)], centre: centre, delta: delta, d: d)[0].a
        let t = Geometry.compose(t0, centre: centre, delta: delta, d: d)
        let r = Geometry.rotate(p, degrees: t.rotation)
        XCTAssertEqual(nudged.x, r.x + t.tx, accuracy: 1e-9)
        XCTAssertEqual(nudged.y, r.y + t.ty, accuracy: 1e-9)
    }
}

final class HouseDocTests: XCTestCase {
    private func doc() throws -> HouseDoc {
        let json = #"""
        {"id":"h","revision":4,"future_field":{"keep":[1,2]},"materials":[{"id":"gypsum","name":"Drywall"},{"id":"brick","name":"Brick"}],
         "walls":[{"id":"w1","level":"L0","a":[0,0],"b":[4,0],"thickness":0.1,"thickness_defaulted":true,"material":"gypsum","material_defaulted":true,
                   "openings":[{"kind":"door","offset":1,"width":0.9,"height":2,"sill":0}],"prov":{"source":"scan","ref":"x#wall/a"}},
                  {"id":"w2","level":"L0","a":[4,0],"b":[4,3],"thickness":0.1,"thickness_defaulted":true,"material":"gypsum","material_defaulted":true,"openings":[]},
                  {"id":"w3","level":"L1","a":[0,0],"b":[2,0],"thickness":0.1,"thickness_defaulted":true,"material":"gypsum","material_defaulted":true,"openings":[]}]}
        """#
        return try HouseDoc(data: Data(json.utf8))
    }

    private func wall(_ d: HouseDoc, _ id: String) throws -> [String: Any] {
        let o = try JSONSerialization.jsonObject(with: try d.data()) as! [String: Any]
        return (o["walls"] as! [[String: Any]]).first { $0["id"] as? String == id }!
    }

    func testUpdateTouchesOnlyWhatWasEdited() throws {
        var d = try doc()
        d.update(wall: "w1", thickness: 0.2, material: "brick")
        let w = try wall(d, "w1")
        XCTAssertEqual(w["thickness"] as? Double, 0.2)
        XCTAssertEqual(w["material"] as? String, "brick")
        XCTAssertEqual(w["thickness_defaulted"] as? Bool, false)
        XCTAssertEqual((w["prov"] as? [String: Any])?["edited"] as? Bool, true)
        XCTAssertEqual((w["prov"] as? [String: Any])?["ref"] as? String, "x#wall/a")      // provenance kept
        XCTAssertEqual(try wall(d, "w2")["thickness"] as? Double, 0.1)                       // other walls untouched
        let o = try JSONSerialization.jsonObject(with: try d.data()) as! [String: Any]
        XCTAssertNotNil(o["future_field"])                                                    // unknown fields go back
        XCTAssertEqual(d.revision, 4)
    }

    func testApplyToDefaultsStaysOnTheFloorAndSkipsEditedWalls() throws {
        var d = try doc()
        d.update(wall: "w1", thickness: 0.3)
        let n = d.applyToDefaults(level: "L0", thickness: 0.15, material: "brick")
        XCTAssertEqual(n, 2)                                                                   // w1 (material still default) and w2
        XCTAssertEqual(try wall(d, "w1")["thickness"] as? Double, 0.3)                        // hand-set thickness kept
        XCTAssertEqual(try wall(d, "w1")["material"] as? String, "brick")
        XCTAssertEqual(try wall(d, "w2")["thickness"] as? Double, 0.15)
        XCTAssertEqual(try wall(d, "w3")["material"] as? String, "gypsum")                    // another floor
    }

    func testOpeningsAreEditedByIndex() throws {
        var d = try doc()
        d.setOpening(wall: "w1", index: 0, kind: "arch", width: 1.2)
        XCTAssertEqual(d.openings(of: "w1"), [HouseDoc.Opening(kind: "arch", width: 1.2)])
        d.removeOpening(wall: "w1", index: 0)
        XCTAssertTrue(d.openings(of: "w1").isEmpty)
    }

    func testMeasureChecksAndAccuracy() throws {
        var d = try doc()
        XCTAssertNil(d.addCheck(what: " ", level: "L0", wall: "w1", scanned: 4, measured: 4))
        d.addCheck(what: "Kitchen north", level: "L0", wall: "w1", scanned: 4.04, measured: 4.0)
        d.addCheck(what: "Hall", level: "L0", wall: "w2", scanned: 2.97, measured: 3.0)
        XCTAssertEqual(d.checks.map(\.id), ["m1", "m2"])
        let a = Accuracy(d.checks)
        XCTAssertEqual(a.count, 2)
        XCTAssertEqual(a.meanAbsPercent, 1.0, accuracy: 1e-9)
        XCTAssertEqual(a.meanSignedPercent, 0.0, accuracy: 1e-9)
        XCTAssertFalse(a.passes)                                                               // fewer than five readings
        let many = (0..<5).map { HouseDoc.Check(id: "m\($0)", what: "x", scanned: 4.02, measured: 4.0) }
        XCTAssertTrue(Accuracy(many).passes)
    }
}

final class PlanItemTests: XCTestCase {
    func testAddingThingsGivesFreshIdsAndKeepsTheRest() throws {
        var d = try HouseDoc(data: Data(#"{"id":"h","revision":1,"outlets":[{"id":"o1","position":[0,0],"level":"L0"}],"levels":[{"id":"L0","name":"G","elevation":0},{"id":"L1","name":"F","elevation":2.8}]}"#.utf8))
        XCTAssertEqual(d.add("outlets", prefix: "o", ["position": [1.0, 2.0], "level": "L0"]), "o2")
        XCTAssertEqual(d.add("jacks", prefix: "j", ["position": [1.0, 2.0], "level": "L0"]), "j1")
        d.set("outlets", "o2", ["z": 0.5])
        XCTAssertEqual(d.item("outlets", "o2")?["z"] as? Double, 0.5)
        XCTAssertEqual((d.item("outlets", "o2")?["prov"] as? [String: Any])?["edited"] as? Bool, true)
        d.remove("outlets", "o1")
        XCTAssertNil(d.item("outlets", "o1"))
        XCTAssertEqual(d.levels.map(\.id), ["L0", "L1"])
    }

    func testStairRectangleAndContains() {
        let r = Geometry.stairRectangle(Pt(0, 0), Pt(0, 3), width: 1)
        XCTAssertTrue(Geometry.contains(Pt(0, 1.5), polygon: r))
        XCTAssertFalse(Geometry.contains(Pt(1, 1.5), polygon: r))
        XCTAssertEqual(Geometry.bounds(r).width, 1, accuracy: 1e-9)
        XCTAssertEqual(Geometry.bounds(r).height, 3, accuracy: 1e-9)
    }

    func testPlanHouseToleratesMissingLists() throws {
        let h = try JSONDecoder().decode(PlanHouse.self, from: Data(#"{"id":"h","name":"H","revision":0,"levels":[]}"#.utf8))
        XCTAssertTrue(h.outlets.isEmpty && h.stairs.isEmpty && h.walls.isEmpty)
    }
}
